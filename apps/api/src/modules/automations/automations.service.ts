import { Injectable, NotFoundException, Logger } from '@nestjs/common';
import { PrismaService } from '../prisma/prisma.service';
import { CreateAutomationRuleDto, AutomationTriggerEnum } from './dto/create-automation-rule.dto';
import { UpdateAutomationRuleDto } from './dto/update-automation-rule.dto';

interface AutomationActionItem {
  type: string;
  params?: Record<string, any>;
}

@Injectable()
export class AutomationsService {
  private readonly logger = new Logger(AutomationsService.name);

  constructor(private readonly prisma: PrismaService) {}

  async findAll(organizationId: string) {
    let rules = await this.prisma.automationRule.findMany({
      where: { organizationId },
      include: {
        _count: {
          select: { executions: true },
        },
      },
      orderBy: { createdAt: 'desc' },
    });

    if (rules.length === 0) {
      await this.seedDefaultRules(organizationId);
      rules = await this.prisma.automationRule.findMany({
        where: { organizationId },
        include: {
          _count: {
            select: { executions: true },
          },
        },
        orderBy: { createdAt: 'desc' },
      });
    }

    return rules;
  }

  async findOne(organizationId: string, id: string) {
    const rule = await this.prisma.automationRule.findFirst({
      where: { id, organizationId },
      include: {
        executions: {
          orderBy: { executedAt: 'desc' },
          take: 20,
        },
      },
    });

    if (!rule) {
      throw new NotFoundException(`Automation rule ${id} not found`);
    }

    return rule;
  }

  async create(organizationId: string, dto: CreateAutomationRuleDto) {
    return this.prisma.automationRule.create({
      data: {
        organizationId,
        name: dto.name,
        description: dto.description,
        triggerEvent: dto.triggerEvent as any,
        conditions: dto.conditions || [],
        actions: dto.actions || [],
        isActive: dto.isActive !== undefined ? dto.isActive : true,
      },
    });
  }

  async update(organizationId: string, id: string, dto: UpdateAutomationRuleDto) {
    await this.findOne(organizationId, id);

    return this.prisma.automationRule.update({
      where: { id },
      data: {
        name: dto.name,
        description: dto.description,
        triggerEvent: dto.triggerEvent ? (dto.triggerEvent as any) : undefined,
        conditions: dto.conditions,
        actions: dto.actions,
        isActive: dto.isActive,
      },
    });
  }

  async toggleStatus(organizationId: string, id: string) {
    const rule = await this.findOne(organizationId, id);
    return this.prisma.automationRule.update({
      where: { id },
      data: { isActive: !rule.isActive },
    });
  }

  async delete(organizationId: string, id: string) {
    await this.findOne(organizationId, id);
    await this.prisma.automationRule.delete({ where: { id } });
    return { success: true, message: 'Automation rule deleted' };
  }

  async getExecutions(organizationId: string, ruleId?: string) {
    const where: any = {};
    if (ruleId) {
      where.ruleId = ruleId;
    }
    where.rule = { organizationId };

    return this.prisma.automationExecution.findMany({
      where,
      include: {
        rule: {
          select: {
            name: true,
            triggerEvent: true,
          },
        },
      },
      orderBy: { executedAt: 'desc' },
      take: 50,
    });
  }

  async triggerEvent(organizationId: string, trigger: AutomationTriggerEnum, payload: any) {
    this.logger.log(`Processing automation trigger: ${trigger} for org: ${organizationId}`);

    const activeRules = await this.prisma.automationRule.findMany({
      where: {
        organizationId,
        triggerEvent: trigger as any,
        isActive: true,
      },
    });

    const executionResults: any[] = [];

    const systemUser = await this.prisma.user.findFirst({
      where: { memberships: { some: { organizationId } } },
    });
    const defaultUserId = payload.userId || systemUser?.id || 'system';

    for (const rule of activeRules) {
      try {
        const actions = Array.isArray(rule.actions)
          ? (rule.actions as unknown as AutomationActionItem[])
          : [];

        for (const action of actions) {
          if (!action) continue;

          if (action.type === 'CREATE_TASK') {
            await this.prisma.activity.create({
              data: {
                organizationId,
                createdById: defaultUserId,
                type: 'TASK',
                title: action.params?.title || `Follow-up: ${payload.title || payload.name || 'Automated task'}`,
                description: action.params?.description || `Auto-generated by rule "${rule.name}"`,
                status: 'PENDING',
                priority: action.params?.priority || 'HIGH',
                dueAt: new Date(Date.now() + (action.params?.dueInHours || 24) * 3600 * 1000),
                leadId: payload.leadId || (payload.entityType === 'LEAD' ? payload.entityId : undefined),
                dealId: payload.dealId || (payload.entityType === 'DEAL' ? payload.entityId : undefined),
                companyId: payload.companyId,
                contactId: payload.contactId,
              },
            });
          } else if (action.type === 'SEND_NOTIFICATION') {
            const users = await this.prisma.user.findMany({
              where: {
                memberships: {
                  some: { organizationId },
                },
              },
              take: 5,
            });

            for (const user of users) {
              await this.prisma.notification.create({
                data: {
                  organizationId,
                  userId: user.id,
                  title: action.params?.title || `Automation: ${rule.name}`,
                  message: action.params?.message || `Triggered by event ${trigger}`,
                  type: 'INFO',
                  actionUrl: payload.link || '/dashboard',
                },
              });
            }
          }
        }

        const execution = await this.prisma.automationExecution.create({
          data: {
            ruleId: rule.id,
            triggerPayload: payload || {},
            status: 'SUCCESS',
          },
        });
        executionResults.push(execution);
      } catch (err: any) {
        this.logger.error(`Failed to execute automation rule ${rule.id}: ${err.message}`);
        const failedExecution = await this.prisma.automationExecution.create({
          data: {
            ruleId: rule.id,
            triggerPayload: payload || {},
            status: 'FAILED',
            errorDetails: err.message,
          },
        });
        executionResults.push(failedExecution);
      }
    }

    return { processedRulesCount: activeRules.length, executions: executionResults };
  }

  private async seedDefaultRules(organizationId: string) {
    const defaultRules = [
      {
        organizationId,
        name: 'Auto-Assign Follow-up Task on New Lead',
        description: 'Automatically creates a high-priority outreach task within 24 hours of receiving a lead.',
        triggerEvent: AutomationTriggerEnum.LEAD_CREATED as any,
        conditions: [],
        actions: [
          {
            type: 'CREATE_TASK',
            params: {
              title: 'Perform Discovery Call & Verify Contact Details',
              priority: 'HIGH',
              dueInHours: 24,
            },
          },
          {
            type: 'SEND_NOTIFICATION',
            params: {
              title: 'New Lead Ingestion Alert',
              message: 'A new prospective lead has entered the sales funnel.',
            },
          },
        ],
        isActive: true,
      },
      {
        organizationId,
        name: 'Deal Stage Progress Notification',
        description: 'Notifies management whenever an opportunity advances in the sales pipeline.',
        triggerEvent: AutomationTriggerEnum.DEAL_STAGE_CHANGED as any,
        conditions: [],
        actions: [
          {
            type: 'SEND_NOTIFICATION',
            params: {
              title: 'Deal Moved Stage',
              message: 'An active opportunity has transitioned stages.',
            },
          },
        ],
        isActive: true,
      },
      {
        organizationId,
        name: 'Escalate Overdue Tasks',
        description: 'Creates system warning notifications when sales activities surpass target deadline.',
        triggerEvent: AutomationTriggerEnum.TASK_OVERDUE as any,
        conditions: [],
        actions: [
          {
            type: 'SEND_NOTIFICATION',
            params: {
              title: 'Critical Task Overdue',
              message: 'A planned customer outreach action has exceeded its due date.',
            },
          },
        ],
        isActive: true,
      },
    ];

    for (const rule of defaultRules) {
      await this.prisma.automationRule.create({ data: rule });
    }
  }
}
